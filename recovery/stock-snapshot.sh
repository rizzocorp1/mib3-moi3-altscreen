#!/bin/sh
# Scoped MOI3 filesystem snapshots. Not a firmware/partition recovery image.
set -eu
umask 077
die() { echo "ERROR: $*" >&2; exit 1; }
[ "$#" -eq 3 ] || die 'usage: stock-snapshot.sh backup|verify|restore ROOT BACKUP_DIRECTORY'
ACTION=$1
ROOT=$(cd "$2" && pwd -P)
BACKUP=$3
case "$BACKUP" in /*) ;; *) die 'backup directory must be absolute';; esac
case "$ROOT" in /) [ "$(id -u)" -eq 0 ] || die 'root privileges required';;
  *) [ "${MOI3_TEST_ROOT:-}" = "$ROOT" ] || die 'non-system root requires MOI3_TEST_ROOT';;
esac
case "$BACKUP/" in "${ROOT%/}/lge/"*|"${ROOT%/}/data/lge/"*|"${ROOT%/}/etc/"*) die 'backup overlaps a managed scope';; esac
for tool in tar sha256sum cmp find sort awk cp mv sync; do command -v "$tool" >/dev/null || die "missing $tool"; done
tar --version | head -1 | grep 'GNU tar' >/dev/null || die 'GNU tar required'
META='--xattrs --xattrs-include=* --acls --numeric-owner'
if [ "${MOI3_TEST_CONTENT_ONLY:-}" = YES ]; then
  [ "$ROOT" != / ] || die 'content-only mode forbidden on system root'
  META='--numeric-owner'
fi
tar_strict() {
  diagnostics=$(mktemp)
  if tar "$@" 2> "$diagnostics"; then status=0; else status=$?; fi
  if [ "$status" -ne 0 ] || [ -s "$diagnostics" ]; then
    cat "$diagnostics" >&2
    rm -f "$diagnostics"
    die 'tar failed or reported warnings; metadata fidelity cannot be assumed'
  fi
  rm -f "$diagnostics"
}
# These scopes cover the legacy installer's reviewed writes, including pairing data.
# Keep in sync with any future installer; unknown writes invalidate this coverage.
scopes() { printf '%s\n' lge/app_rw/smartlink/carplay lge/app_rw/lib64/altscreen_handler.so data/lge/smartlink etc/vw_fs_reboot.sh; }
check_ancestors() {
  scopes | while IFS= read -r scope; do
    parent=${scope%/*}
    while [ "$parent" != . ]; do
      [ ! -L "$ROOT/$parent" ] || die "symlink ancestor: $parent"
      case "$parent" in */*) parent=${parent%/*};; *) parent=.;; esac
    done
  done
}
identity() {
  [ -f "$ROOT/etc/machine-id" ] || die 'machine-id required'
  [ -f "$ROOT/etc/os-release" ] || die 'os-release required'
  (cd "$ROOT"; sha256sum etc/machine-id etc/os-release)
}
verify() {
  [ -f "$BACKUP/COMPLETE" ] || die 'incomplete snapshot'
  (cd "$BACKUP"; sha256sum -c checksums.sha256) || die 'snapshot integrity check failed'
  expected=$(scopes)
  actual=$(cat "$BACKUP/scopes.txt")
  [ "$actual" = "$expected" ] || die 'scope list mismatch'
  current=$(identity)
  [ "$current" = "$(cat "$BACKUP/identity.sha256")" ] || die 'unit/OS identity mismatch'
  # Archives are generated by this tool and must stay on trusted offline media.
  tar -tf "$BACKUP/stock.tar" | awk '
    /^\// || /(^|\/)\.\.(\/|$)/ { bad=1 }
    !/^(lge\/app_rw\/smartlink\/carplay(\/|$)|lge\/app_rw\/lib64\/altscreen_handler[.]so$|data\/lge\/smartlink(\/|$)|etc\/vw_fs_reboot[.]sh$)/ { bad=1 }
    END {exit bad}' || die 'archive contains an out-of-scope path'
}
check_ancestors
case "$ACTION" in
backup)
  [ ! -e "$BACKUP" ] || die 'refusing to overwrite an existing snapshot'
  mkdir -m 700 "$BACKUP"
  scopes > "$BACKUP/scopes.txt"
  identity > "$BACKUP/identity.sha256"
  : > "$BACKUP/present.txt"
  : > "$BACKUP/absent.txt"
  scopes | while IFS= read -r scope; do
    if [ -e "$ROOT/$scope" ] || [ -L "$ROOT/$scope" ]; then
      printf '%s\n' "$scope" >> "$BACKUP/present.txt"
    else printf '%s\n' "$scope" >> "$BACKUP/absent.txt"; fi
  done
  # Do not ignore changed-file/read errors: a live, changing tree is not a baseline.
  tar_strict $META -cpf "$BACKUP/stock.tar" -C "$ROOT" -T "$BACKUP/present.txt"
  tar_strict $META -df "$BACKUP/stock.tar" -C "$ROOT"
  (cd "$BACKUP"; sha256sum stock.tar scopes.txt identity.sha256 present.txt absent.txt > checksums.sha256)
  sync
  printf 'scoped-snapshot-v1\n' > "$BACKUP/COMPLETE"
  sync
  verify
  echo 'Snapshot verified. Store a second copy offline before any experiment.'
  ;;
verify) verify; echo 'Snapshot integrity and unit/OS identity verified.';;
restore)
  verify
  # This flag is an operator assertion, NOT a substitute for platform validation.
  [ "${MOI3_SERVICES_STOPPED:-}" = YES ] || die 'stop CarPlay/native stream services and set MOI3_SERVICES_STOPPED=YES'
  [ "${MOI3_FIRMWARE_MATCH_CONFIRMED:-}" = YES ] || die 'confirm exact firmware still matches baseline; set MOI3_FIRMWARE_MATCH_CONFIRMED=YES'
  if [ "$ROOT" = / ]; then
    # Active bind mounts can hide files or redirect writes. Refuse all mounts in scopes.
    if awk '{print $5}' /proc/self/mountinfo | grep -E '^/(lge/app_rw/smartlink/carplay|lge/app_rw/lib64/altscreen_handler[.]so|data/lge/smartlink|etc/vw_fs_reboot[.]sh)(/|$)'; then
      die 'unmount managed scopes first'
    fi
  fi
  [ ! -e "$BACKUP/restore-in-progress" ] || die 'interrupted restore requires manual recovery; preserve journal'
  mkdir "$BACKUP/restore-in-progress"
  STAGE="$BACKUP/restore-in-progress/stage"
  mkdir "$STAGE"
  tar_strict $META -xpf "$BACKUP/stock.tar" -C "$STAGE"
  tar_strict $META -df "$BACKUP/stock.tar" -C "$STAGE"
  # Journal every scope. Old trees stay beside their originals until verification.
  scopes | while IFS= read -r scope; do
    target="$ROOT/$scope"
    [ ! -e "$target.moi3-rollback" ] && [ ! -L "$target.moi3-rollback" ] || die "quarantine exists: $scope"
    [ ! -e "$target.moi3-staged" ] && [ ! -L "$target.moi3-staged" ] || die "staging exists: $scope"
    mkdir -p "${target%/*}"
    if [ -e "$STAGE/$scope" ] || [ -L "$STAGE/$scope" ]; then
      cp -a --preserve=all "$STAGE/$scope" "$target.moi3-staged"
    fi
    printf '%s\n' "$scope" >> "$BACKUP/restore-in-progress/journal"
    if [ -e "$target" ] || [ -L "$target" ]; then mv "$target" "$target.moi3-rollback"; fi
    if [ -e "$target.moi3-staged" ] || [ -L "$target.moi3-staged" ]; then mv "$target.moi3-staged" "$target"; fi
    sync
  done
  tar_strict $META -df "$BACKUP/stock.tar" -C "$ROOT"
  while IFS= read -r scope; do
    [ ! -e "$ROOT/$scope" ] && [ ! -L "$ROOT/$scope" ] || die "expected absent: $scope"
  done < "$BACKUP/absent.txt"
  # Leave quarantined trees and journal for inspection; never auto-reboot on failure.
  printf 'Restored and verified recorded contents/metadata. Quarantines retained.\n' > "$BACKUP/restore-in-progress/VERIFIED"
  sync
  echo 'Scoped restore verified. Inspect journal/quarantines before restarting services.'
  ;;
*) die 'unknown action';;
esac
